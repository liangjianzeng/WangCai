/// 格式：`<name>/SKILL.md`（frontmatter：name/description/whenToUse/invocation）。
///
/// 写法规范（对齐 anthropics/skills 官方实践，2026-10-01 调研定案）：
/// - description/whenToUse 必须一行短句——目录（availableSkillsText）每回合
///   注入系统提示词，是唯一常驻 prefill 成本；
/// - body 是 load_skill **按需加载**的执行手册，要写厚：工作流步骤 + 模板 +
///   验收清单，目标 40~90 行——写 3 句话的技能等于没有技能；
/// - 正文只绑定本 app 真实存在的工具名，不写空泛指引。
library;

const int kRankBuiltin = 100;
const int kRankUser = 200;

final class Skill {
  const Skill({
    required this.name,
    required this.description,
    required this.whenToUse,
    this.invocation,
    required this.body,
    required this.rank,
  });

  final String name;
  final String description;
  final String whenToUse;
  final String? invocation;
  final String body;
  final int rank;

  factory Skill.parse(String content, {required String name}) {
    final lines = content.split('\n');
    final meta = <String, String>{};
    int startBody = 0;
    bool done = false;
    for (var i = 0; i < lines.length; i++) {
      if (done) break;
      final raw = lines[i];
      final line = raw.trim();
      if (line.startsWith('#')) continue;
      if (line == '---') {
        // frontmatter 分隔线：正文从下一行开始。
        startBody = i + 1;
        done = true;
        break;
      }
      final colon = line.indexOf(':');
      if (colon > 0) {
        final key = line.substring(0, colon).trim();
        if (key != '') {
          meta[key] = _clean(line.substring(colon + 1));
        }
      } else {
        startBody = i;
        done = true;
      }
    }
    final body = lines.sublist(startBody).join('\n').trim();
    return Skill(
      name: name,
      description: meta['description'] ?? '',
      whenToUse: meta['whenToUse'] ?? meta['when_to_use'] ?? '',
      invocation: meta['invocation'],
      body: body,
      rank: 0,
    );
  }

  Skill withRank(int rank) => Skill(
        name: name,
        description: description,
        whenToUse: whenToUse,
        invocation: invocation,
        body: body,
        rank: rank,
      );

  String injectionText() {
    final sb = StringBuffer();
    sb.writeln('name: $name');
    sb.writeln('description: $description');
    sb.writeln('whenToUse: $whenToUse');
    if (invocation != null) {
      sb.writeln('invocation: $invocation');
    }
    return sb.toString();
  }
}

String _clean(String s) {
  var r = s.trim();
  if (r.length >= 2 && r.startsWith('"') && r.endsWith('"')) {
    r = r.substring(1, r.length - 1).trim();
  }
  return r;
}

